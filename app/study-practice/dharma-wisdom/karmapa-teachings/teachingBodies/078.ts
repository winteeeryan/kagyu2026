    "五、蓮花",
    "蓮花生於淤泥而潔淨不染，代表眾生本具之清淨心。蓮花妙香廣布，常用以比喻佛菩薩的慈悲莊嚴、功行流布。又比喻佛出五濁惡世，如蓮出淤泥而不染，清淨莊嚴。\n《悲華經》及《妙法蓮華經》即以此花為經題。\n佛經中，蓮花略分為三種：\n（一）缽頭摩華（梵名padma）：意譯為赤蓮花或黃蓮花。\n（二）優缽羅華（梵名utpala）：意譯為青蓮花。經典中以其葉形容佛眼之微妙；以其花形容佛口氣之香潔。\n（三）芬陀利華（梵名pundarika）：意譯為白蓮花。比喻將染污之煩惱昇華為清淨無垢之法性。",
