function buildBlocks(source: string): EncyclopediaBlock[] {
  let centerPraiseText = false;

  return source
    .trim()
    .split(/\n+/)
    .map((line) => line.trim())
    .filter((line) => line && line !== "佛學小百科")
    .map((line) => {
      const sectionMatch = line.match(/^[一二三四五六七八九十]+、(.+)$/);

      if (line === "佛陀十二相成道讚頌" || sectionMatch) {
        centerPraiseText = line === "佛陀十二相成道讚頌";

        return {
          kind: "heading",
          text: sectionMatch?.[1] ?? line,
        };
      }

      return {
        align: centerPraiseText ? "center" : undefined,
        kind: "paragraph",
        text: line,
      };
    });
}

